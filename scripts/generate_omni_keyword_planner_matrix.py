def calculate_opportunity_score(kw_dict):
    vol = kw_dict["monthly_searches"]
    comp_idx = kw_dict["competition_index"]
    avg_cpc = (kw_dict["cpc_low_inr"] + kw_dict["cpc_high_inr"]) / 2.0
    growth = float(kw_dict["three_month_change"].replace("+", "").replace("%", ""))
    
    score = (vol / 500.0) * (avg_cpc / 100.0) * (growth / 100.0) * ((100 - comp_idx) / 30.0)
    return round(score, 2)

